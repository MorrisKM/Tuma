//! The docs model as one HTML file with its styles and a little script inline, so it can be opened, mailed or hosted
//! as it is: a searchable list of requests on the left, each request's details on the right, light and dark themes.

use std::fmt::Write;

use super::{Api, Endpoint, Kind, Param, Payload};

fn esc(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

/// Paragraphs, with `code` spans, from plain or lightly marked-up text.
fn prose(text: &str) -> String {
    text.trim()
        .split("\n\n")
        .map(|p| {
            let mut out = String::new();
            for (i, part) in esc(p).split('`').enumerate() {
                if i % 2 == 1 {
                    let _ = write!(out, "<code>{part}</code>");
                } else {
                    out.push_str(&part.replace('\n', "<br>"));
                }
            }
            format!("<p>{out}</p>")
        })
        .collect()
}

fn id(group: usize, endpoint: usize) -> String {
    format!("e{group}-{endpoint}")
}

pub fn render(api: &Api) -> String {
    let mut nav = String::new();
    let mut main = String::new();
    for (gi, group) in api.groups.iter().enumerate() {
        if !group.name.is_empty() {
            let _ = write!(nav, "<div class=\"nav-group\">{}</div>", esc(&group.name));
            let _ = write!(main, "<h2 class=\"group\">{}</h2>", esc(&group.name));
            if !group.description.is_empty() {
                main.push_str(&prose(&group.description));
            }
        }
        for (ei, e) in group.endpoints.iter().enumerate() {
            let _ = write!(
                nav,
                "<a class=\"nav-item\" href=\"#{id}\" data-search=\"{search}\"><span class=\"m m-{class}\">{method}</span>{name}</a>",
                id = id(gi, ei),
                search = esc(&format!("{} {} {}", e.name, e.method, e.path).to_lowercase()),
                class = e.method.to_ascii_lowercase(),
                method = esc(short(&e.method)),
                name = esc(&e.name),
            );
            endpoint(&mut main, e, &id(gi, ei));
        }
    }
    let servers = if api.servers.is_empty() {
        String::new()
    } else {
        format!(
            "<div class=\"servers\"><span>Base URL</span>{}</div>",
            api.servers
                .iter()
                .map(|s| format!("<code>{}</code>", esc(s)))
                .collect::<String>()
        )
    };
    let count: usize = api.groups.iter().map(|g| g.endpoints.len()).sum();
    format!(
        r#"<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>{STYLE}</style>
</head>
<body>
<aside>
  <div class="brand">{title}</div>
  <input id="search" type="search" placeholder="Filter {count} requests" aria-label="Filter requests">
  <nav>{nav}</nav>
  <div class="made">Generated by Tuma</div>
</aside>
<main>
  <header>
    <h1>{title}</h1>
    {description}
    {servers}
  </header>
  {main}
</main>
<script>{SCRIPT}</script>
</body>
</html>
"#,
        title = esc(&api.title),
        description = prose(&api.description),
    )
}

fn short(method: &str) -> &str {
    match method {
        "DELETE" => "DEL",
        "OPTIONS" => "OPT",
        m => m,
    }
}

fn endpoint(out: &mut String, e: &Endpoint, id: &str) {
    let target = match e.kind {
        Kind::Grpc => e.grpc_method.clone().unwrap_or_else(|| e.path.clone()),
        _ => e.path.clone(),
    };
    let _ = write!(
        out,
        "<section class=\"endpoint\" id=\"{id}\"><h3>{name}</h3><div class=\"sig\"><span class=\"m m-{class}\">{method}</span><code>{target}</code></div>",
        name = esc(&e.name),
        class = e.method.to_ascii_lowercase(),
        method = esc(&e.method),
        target = esc(&target),
    );
    if !e.description.is_empty() {
        out.push_str(&prose(&e.description));
    }
    if let Some(auth) = &e.auth {
        let _ = write!(
            out,
            "<div class=\"fact\"><span>Auth</span>{}</div>",
            prose(&auth.describe())
        );
    }
    params(out, "Path parameters", &e.path_params);
    params(out, "Query parameters", &e.query);
    params(out, "Headers", &e.headers);
    if let Some(body) = &e.body {
        let _ = write!(
            out,
            "<h4>Request body <small>{}</small></h4>",
            esc(&body.content_type)
        );
        code(out, body);
    }
    if !e.responses.is_empty() {
        let _ = write!(out, "<h4>Responses</h4>");
        for r in &e.responses {
            let tone = if r.status < 300 {
                "ok"
            } else if r.status < 400 {
                "redirect"
            } else {
                "fail"
            };
            match &r.body {
                Some(body) => {
                    let _ = write!(
                        out,
                        "<details><summary><span class=\"status {tone}\">{}</span>{} <small>{}</small></summary>",
                        r.status,
                        esc(&r.name),
                        esc(&body.content_type)
                    );
                    code(out, body);
                    out.push_str("</details>");
                }
                None => {
                    let _ = write!(
                        out,
                        "<div class=\"response\"><span class=\"status {tone}\">{}</span>{}</div>",
                        r.status,
                        esc(&r.name)
                    );
                }
            }
        }
    } else if e.kind == Kind::Http {
        out.push_str("<p class=\"none\">No example responses saved yet.</p>");
    }
    out.push_str("</section>");
}

fn params(out: &mut String, title: &str, list: &[Param]) {
    if list.is_empty() {
        return;
    }
    let _ = write!(out, "<h4>{title}</h4><table><tbody>");
    for p in list {
        let _ = write!(
            out,
            "<tr><th><code>{}</code></th><td>{}</td></tr>",
            esc(&p.name),
            if p.example.is_empty() {
                String::new()
            } else {
                format!("<code>{}</code>", esc(&p.example))
            }
        );
    }
    out.push_str("</tbody></table>");
}

fn code(out: &mut String, body: &Payload) {
    let _ = write!(
        out,
        "<div class=\"code\"><button class=\"copy\" type=\"button\">Copy</button><pre>{}</pre></div>",
        esc(&body.example)
    );
}

